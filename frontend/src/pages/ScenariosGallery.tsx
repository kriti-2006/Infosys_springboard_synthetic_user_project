import { useNavigate } from "react-router-dom";
import { useMutation, useQuery } from "@tanstack/react-query";
import { scenariosApi } from "../api/scenarios";
import { errorMessage } from "../api/client";
import { PageHeader } from "../components/ui/PageHeader";
import { Card, CardBody } from "../components/ui/Card";
import { Button } from "../components/ui/Button";
import { Badge } from "../components/ui/Badge";
import { SkeletonCard } from "../components/ui/Skeleton";
import { useToast } from "../components/ui/Toast";
import "./ScenariosGallery.css";

export function ScenariosGallery() {
  const navigate = useNavigate();
  const toast = useToast();

  const { data, isLoading } = useQuery({ queryKey: ["scenarios"], queryFn: scenariosApi.list });

  const launch = useMutation({
    mutationFn: (slug: string) => scenariosApi.launch(slug),
    onSuccess: (res) => {
      toast.show(`Launched "${res.experiment.name}"`, "success");
      navigate(`/experiments/${res.experiment.id}`, { state: { suggestedQuestions: res.suggestedQuestions } });
    },
    onError: (err) => toast.show(errorMessage(err), "error"),
  });

  return (
    <div>
      <PageHeader
        title="Sample scenarios"
        subtitle="Ready-made product + audience setups across common domains. Launching one creates a real experiment — personas and survey responses are still generated by the real agents, not faked."
      />
      {isLoading && (
        <div className="scenarios-grid">
          <SkeletonCard />
          <SkeletonCard />
          <SkeletonCard />
        </div>
      )}
      {data && (
        <div className="scenarios-grid">
          {data.map((s) => (
            <Card key={s.slug}>
              <CardBody>
                <Badge tone="violet">{s.domain}</Badge>
                <div className="scenario-card-title">{s.title}</div>
                <p className="scenario-card-desc">{s.description}</p>
                <Button
                  variant="secondary"
                  loading={launch.isPending && launch.variables === s.slug}
                  onClick={() => launch.mutate(s.slug)}
                  style={{ marginTop: 14 }}
                >
                  Launch this scenario
                </Button>
              </CardBody>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}
